export type CourseStatus = "pending" | "approved" | "rejected" | string;

export interface CourseRow {
  id: string;
  creator: string;
  courseTitle: string;
  courseId: string;
  category: string;
  difficultyLevel: string;
  dateApproved: string;
  dateCreated?: string;
  hasVideo: boolean;
  isAi: boolean;
  status: CourseStatus;
  /** Modules in the submission — the headline number on the grid card. */
  moduleCount: number;
  lessonCount: number;
}

/** Avatar colours for creator initials, mirroring `userColors` in TeamsView. */
export const creatorColors = [
  "#0A60E1",
  "#FF8A00",
  "#00C48C",
  "#FF3D57",
  "#7C3AED",
  "#14B8A6",
  "#8B5CF6",
  "#F59E0B",
];

export const colorForCreator = (name: string) => {
  const sum = name.split("").reduce((total, char) => total + char.charCodeAt(0), 0);
  return creatorColors[sum % creatorColors.length];
};

export const initialsFor = (name: string) =>
  name
    .split(" ")
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() ?? "")
    .join("");

